import "@testing-library/jest-dom/vitest";
import { afterEach } from "vitest";
import { cleanup } from "@testing-library/react";

afterEach(() => {
  cleanup();
});

// jsdom doesn't implement ResizeObserver; Canvas uses it to zoom-to-fit
// whenever its viewport element resizes. A no-op observer is enough for
// tests, which don't rely on layout-driven resize callbacks firing.
if (typeof globalThis.ResizeObserver === "undefined") {
  globalThis.ResizeObserver = class {
    observe(): void {}
    unobserve(): void {}
    disconnect(): void {}
  };
}
